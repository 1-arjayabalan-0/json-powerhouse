/**
 * Renders a relational model as a Prisma schema: one model per table, with
 * relations, @id/@unique, and @map/@@map back to snake_case database names.
 */
import { camelCase, pascalCase, rootRecords, singular, uniqueName } from './infer';
import { buildRelationalModel, type Column, type ColumnType, type NestedStrategy, type ScalarColumnType, type Table } from './relational';

export type PrismaProvider = 'postgresql' | 'mysql' | 'sqlite';

export interface PrismaOptions {
    modelName: string;
    provider: PrismaProvider;
    nested: NestedStrategy;
    mapNames: boolean;
    includeHeader: boolean;
}

interface Field { name: string; type: string; attrs: string[]; doc?: string }

function scalarPrisma(t: ScalarColumnType, p: PrismaProvider): { type: string; attrs: string[] } {
    switch (t.kind) {
        case 'int': return { type: t.big ? 'BigInt' : 'Int', attrs: [] };
        case 'float': return { type: 'Float', attrs: [] };
        case 'bool': return { type: 'Boolean', attrs: [] };
        case 'string': return { type: 'String', attrs: p === 'mysql' && t.maxLength > 191 ? ['@db.Text'] : [] };
        case 'date': return { type: 'DateTime', attrs: p === 'sqlite' ? [] : ['@db.Date'] };
        case 'datetime': return { type: 'DateTime', attrs: p === 'postgresql' && t.zoned ? ['@db.Timestamptz(3)'] : [] };
        case 'uuid': return { type: 'String', attrs: p === 'postgresql' ? ['@db.Uuid'] : [] };
    }
}

function fieldType(t: ColumnType, p: PrismaProvider): { type: string; attrs: string[]; list?: boolean; doc?: string } {
    if (t.kind === 'json') {
        return p === 'sqlite' ? { type: 'String', attrs: [], doc: 'JSON stored as text' } : { type: 'Json', attrs: [] };
    }
    if (t.kind === 'array') {
        if (p === 'postgresql') return { ...scalarPrisma(t.of, p), list: true };
        return p === 'sqlite' ? { type: 'String', attrs: [], doc: 'JSON array stored as text' } : { type: 'Json', attrs: [] };
    }
    return scalarPrisma(t, p);
}

function modelNameOf(table: Table, root: Table, opts: PrismaOptions): string {
    if (table === root && opts.modelName.trim()) return pascalCase(opts.modelName.trim());
    return pascalCase(singular(table.name));
}

export function generatePrismaSchema(json: string, opts: PrismaOptions): string {
    const { records } = rootRecords(json);
    const tables = buildRelationalModel(records, { rootName: opts.modelName || 'items', nested: opts.nested });
    const root = tables[0];
    const p = opts.provider;

    const modelNames = new Map<Table, string>();
    const takenModels = new Set<string>();
    for (const t of tables) modelNames.set(t, uniqueName(modelNameOf(t, root, opts), takenModels, ''));

    // Field names per table, reserved up front so relation fields never clash.
    const fieldNames = new Map<Table, Set<string>>(tables.map(t => [t, new Set<string>()]));
    const colField = new Map<Column, string>();
    for (const t of tables) {
        for (const c of t.columns) colField.set(c, uniqueName(camelCase(c.key ?? c.name), fieldNames.get(t)!, ''));
    }
    const backRelation = new Map<Table, string>();
    const childRelation = new Map<Table, string>();
    for (const t of tables) {
        if (!t.parent) continue;
        backRelation.set(t, uniqueName(camelCase(singular(t.parent.name)), fieldNames.get(t)!, ''));
        childRelation.set(t, uniqueName(camelCase(t.parentKey ?? t.name), fieldNames.get(t.parent)!, ''));
    }

    const blocks: string[] = [];
    if (opts.includeHeader) {
        blocks.push([
            '// Prisma schema generated by JSON PowerHouse',
            'generator client {',
            '  provider = "prisma-client-js"',
            '}',
            '',
            'datasource db {',
            `  provider = "${p}"`,
            '  url      = env("DATABASE_URL") // Prisma 7+: set the URL in prisma.config.ts instead',
            '}',
        ].join('\n'));
    }

    for (const t of tables) {
        const fields: Field[] = [];
        for (const c of t.columns) {
            const name = colField.get(c)!;
            const ft = fieldType(c.type, p);
            const attrs: string[] = [];
            if (c.primary) {
                attrs.push('@id');
                if (c.generated) attrs.push('@default(autoincrement())');
            }
            if (c.references?.unique) attrs.push('@unique');
            attrs.push(...ft.attrs);
            if (opts.mapNames && name !== c.name) attrs.push(`@map("${c.name}")`);
            let type = ft.type;
            // Surrogate keys (and foreign keys to them) use Int to match @default(autoincrement()).
            if (c.generated || c.references?.table.pk.generated) type = 'Int';
            if (ft.list) type += '[]';
            else if (c.nullable) type += '?';
            fields.push({ name, type, attrs, doc: ft.doc });
        }
        if (t.parent && t.fk) {
            fields.push({
                name: backRelation.get(t)!,
                type: modelNames.get(t.parent)!,
                attrs: [`@relation(fields: [${colField.get(t.fk)}], references: [${colField.get(t.parent.pk)}], onDelete: Cascade)`],
            });
        }
        for (const child of t.children) {
            fields.push({
                name: childRelation.get(child)!,
                type: modelNames.get(child)! + (child.relation === 'many' ? '[]' : '?'),
                attrs: [],
            });
        }

        const nameW = Math.max(...fields.map(f => f.name.length));
        const typeW = Math.max(...fields.map(f => f.type.length));
        const lines: string[] = [];
        for (const f of fields) {
            if (f.doc) lines.push(`  /// ${f.doc}`);
            lines.push(`  ${f.name.padEnd(nameW)} ${f.attrs.length ? f.type.padEnd(typeW) + ' ' + f.attrs.join(' ') : f.type}`.trimEnd());
        }
        const model = modelNames.get(t)!;
        if (opts.mapNames && model !== t.name) {
            lines.push('');
            lines.push(`  @@map("${t.name}")`);
        }
        blocks.push(`model ${model} {\n${lines.join('\n')}\n}`);
    }
    return blocks.join('\n\n') + '\n';
}
