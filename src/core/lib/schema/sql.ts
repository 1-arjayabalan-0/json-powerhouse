/**
 * Renders a relational model as CREATE TABLE (and optional INSERT) statements
 * for PostgreSQL, MySQL or SQLite.
 */
import { rootRecords } from './infer';
import { buildRelationalModel, type Column, type ColumnType, type NestedStrategy, type ScalarColumnType, type Table } from './relational';

export type SqlDialect = 'postgresql' | 'mysql' | 'sqlite';

export interface SqlOptions {
    dialect: SqlDialect;
    tableName: string;
    nested: NestedStrategy;
    includeInserts: boolean;
    ifNotExists: boolean;
}

export const MAX_INSERT_ROWS = 1000;

const RESERVED = new Set([
    'all', 'alter', 'analyze', 'and', 'any', 'array', 'as', 'asc', 'between', 'both', 'by', 'case', 'cast', 'check',
    'collate', 'column', 'comment', 'constraint', 'create', 'cross', 'current_date', 'current_time', 'current_timestamp',
    'current_user', 'database', 'default', 'delete', 'desc', 'distinct', 'div', 'do', 'drop', 'else', 'end', 'except',
    'exists', 'false', 'fetch', 'for', 'foreign', 'from', 'full', 'grant', 'group', 'having', 'if', 'in', 'index',
    'inner', 'insert', 'intersect', 'interval', 'into', 'is', 'join', 'key', 'keys', 'leading', 'left', 'like', 'limit',
    'lock', 'match', 'natural', 'not', 'null', 'of', 'offset', 'on', 'only', 'or', 'order', 'outer', 'primary', 'range',
    'rank', 'references', 'regexp', 'rename', 'replace', 'returning', 'right', 'row', 'rows', 'select', 'session_user',
    'set', 'some', 'table', 'then', 'to', 'trailing', 'true', 'union', 'unique', 'update', 'usage', 'user', 'using',
    'values', 'when', 'where', 'window', 'with',
]);

export function quoteIdent(name: string, dialect: SqlDialect): string {
    if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name)) return name;
    return dialect === 'mysql' ? `\`${name.replace(/`/g, '``')}\`` : `"${name.replace(/"/g, '""')}"`;
}

function isKey(col: Column): boolean {
    return Boolean(col.primary || col.references);
}

function scalarSql(t: ScalarColumnType, dialect: SqlDialect, key: boolean): string {
    switch (dialect) {
        case 'postgresql':
            switch (t.kind) {
                case 'int': return t.big ? 'BIGINT' : 'INTEGER';
                case 'float': return 'DOUBLE PRECISION';
                case 'bool': return 'BOOLEAN';
                case 'string': return 'TEXT';
                case 'date': return 'DATE';
                case 'datetime': return t.zoned ? 'TIMESTAMPTZ' : 'TIMESTAMP';
                case 'uuid': return 'UUID';
            }
            break;
        case 'mysql':
            switch (t.kind) {
                case 'int': return t.big ? 'BIGINT' : 'INT';
                case 'float': return 'DOUBLE';
                case 'bool': return 'BOOLEAN';
                case 'string':
                    if (key || t.maxLength <= 255) return 'VARCHAR(255)';
                    return t.maxLength <= 65535 ? 'TEXT' : 'LONGTEXT';
                case 'date': return 'DATE';
                case 'datetime': return 'DATETIME';
                case 'uuid': return 'CHAR(36)';
            }
            break;
        case 'sqlite':
            switch (t.kind) {
                case 'int': case 'bool': return 'INTEGER';
                case 'float': return 'REAL';
                default: return 'TEXT';
            }
    }
    return 'TEXT';
}

export function columnSql(t: ColumnType, dialect: SqlDialect, key = false): string {
    if (t.kind === 'json') return dialect === 'postgresql' ? 'JSONB' : dialect === 'mysql' ? 'JSON' : 'TEXT';
    if (t.kind === 'array') return dialect === 'postgresql' ? `${scalarSql(t.of, dialect, false)}[]` : dialect === 'mysql' ? 'JSON' : 'TEXT';
    return scalarSql(t, dialect, key);
}

function columnLine(col: Column, dialect: SqlDialect): string {
    const name = quoteIdent(col.name, dialect);
    if (col.generated) {
        if (dialect === 'postgresql') return `${name} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
        if (dialect === 'mysql') return `${name} BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY`;
        return `${name} INTEGER PRIMARY KEY AUTOINCREMENT`;
    }
    let line = `${name} ${columnSql(col.type, dialect, isKey(col))}`;
    if (!col.nullable) line += ' NOT NULL';
    if (col.primary) line += ' PRIMARY KEY';
    if (col.references?.unique) line += ' UNIQUE';
    return line;
}

export function quoteString(s: string, dialect: SqlDialect): string {
    const escaped = dialect === 'mysql' ? s.replace(/\\/g, '\\\\') : s;
    return `'${escaped.replace(/'/g, "''")}'`;
}

function pad(n: number, w = 2): string {
    return String(n).padStart(w, '0');
}

/** MySQL DATETIME rejects zone suffixes, so zoned values are converted to UTC. */
function mysqlDateTime(s: string): string {
    if (/(Z|[+-]\d{2}:?\d{2})$/i.test(s)) {
        const d = new Date(s);
        if (!Number.isNaN(d.getTime())) {
            return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
        }
    }
    return s.replace('T', ' ');
}

function pgArrayLiteral(values: unknown[]): string {
    return `{${values.map(v => {
        if (typeof v === 'string') return `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
        return String(v);
    }).join(',')}}`;
}

export function valueSql(v: unknown, t: ColumnType, dialect: SqlDialect): string {
    if (v === null || v === undefined) return 'NULL';
    if (t.kind === 'json') return quoteString(JSON.stringify(v), dialect);
    if (t.kind === 'array') {
        if (!Array.isArray(v)) return 'NULL';
        return quoteString(dialect === 'postgresql' ? pgArrayLiteral(v) : JSON.stringify(v), dialect);
    }
    if (typeof v === 'boolean') return dialect === 'sqlite' ? (v ? '1' : '0') : v ? 'TRUE' : 'FALSE';
    if (typeof v === 'number' && (t.kind === 'int' || t.kind === 'float')) return String(v);
    if (typeof v === 'object') return quoteString(JSON.stringify(v), dialect);
    if (t.kind === 'datetime' && dialect === 'mysql' && typeof v === 'string') return quoteString(mysqlDateTime(v), dialect);
    return quoteString(String(v), dialect);
}

const DIALECT_NAME: Record<SqlDialect, string> = { postgresql: 'PostgreSQL', mysql: 'MySQL', sqlite: 'SQLite' };

function createTable(table: Table, opts: SqlOptions): string[] {
    const d = opts.dialect;
    const lines = table.columns.map(c => columnLine(c, d));
    if (table.fk && table.parent) {
        lines.push(`FOREIGN KEY (${quoteIdent(table.fk.name, d)}) REFERENCES ${quoteIdent(table.parent.name, d)} (${quoteIdent(table.parent.pk.name, d)}) ON DELETE CASCADE`);
    }
    const out = [
        `CREATE TABLE ${opts.ifNotExists ? 'IF NOT EXISTS ' : ''}${quoteIdent(table.name, d)} (`,
        lines.map(l => `    ${l}`).join(',\n'),
        ');',
    ];
    // InnoDB indexes foreign keys automatically; PostgreSQL and SQLite do not.
    if (table.fk && table.relation === 'many' && d !== 'mysql') {
        out.push(`CREATE INDEX ${opts.ifNotExists ? 'IF NOT EXISTS ' : ''}${quoteIdent(`idx_${table.name}_${table.fk.name}`, d)} ON ${quoteIdent(table.name, d)} (${quoteIdent(table.fk.name, d)});`);
    }
    return out;
}

function inserts(table: Table, opts: SqlOptions): string[] {
    if (!table.rows.length) return [];
    const d = opts.dialect;
    const rows = table.rows.slice(0, MAX_INSERT_ROWS);
    const out = [
        `INSERT INTO ${quoteIdent(table.name, d)} (${table.columns.map(c => quoteIdent(c.name, d)).join(', ')}) VALUES`,
        rows.map(r => `    (${r.map((v, i) => valueSql(v, table.columns[i].type, d)).join(', ')})`).join(',\n') + ';',
    ];
    if (table.rows.length > rows.length) out.push(`-- ${table.rows.length - rows.length} more rows omitted`);
    if (d === 'postgresql' && table.pk.generated) {
        const t = quoteIdent(table.name, d), c = quoteIdent(table.pk.name, d);
        out.push(`SELECT setval(pg_get_serial_sequence(${quoteString(t, d)}, ${quoteString(table.pk.name, d)}), (SELECT MAX(${c}) FROM ${t}));`);
    }
    return out;
}

export function generateSqlSchema(json: string, opts: SqlOptions): string {
    const { records } = rootRecords(json);
    const tables = buildRelationalModel(records, { rootName: opts.tableName, nested: opts.nested });
    const parts: string[] = [`-- ${DIALECT_NAME[opts.dialect]} schema generated by JSON PowerHouse`];
    if (opts.dialect === 'sqlite' && tables.some(t => t.fk)) parts.push('PRAGMA foreign_keys = ON;');
    for (const t of tables) parts.push(createTable(t, opts).join('\n'));
    if (opts.includeInserts) {
        for (const t of tables) {
            const ins = inserts(t, opts);
            if (ins.length) parts.push(ins.join('\n'));
        }
    }
    return parts.join('\n\n') + '\n';
}
